-- AP5: Historie der Uebergaben an das lokale E-Mail-Programm (mailto:).
--
-- Docker fuehrt diese Datei NUR beim ersten Initialisieren eines leeren
-- Datenbank-Volumes aus (wie 001_create_centers.sql). Bei einer bereits
-- bestehenden Datenbank legt die App dieselbe Tabelle beim Start an
-- (app/mail_models.py, ensure_mail_history_table, mit Sperre gegen parallele
-- Gunicorn-Worker). Beide Wege erzeugen dasselbe Schema; die Tests in
-- tests/test_mail.py vergleichen die Spalten dieser Datei mit dem ORM-Modell.
--
-- Diese Datei aendert centers, services und center_services NICHT.
--
-- status ist immer 'handoff_attempted': mailto: kann nicht bestaetigen, dass
-- die Mail im Mailprogramm wirklich abgeschickt wurde.
-- recipient_count ist auf 1 bis 20 begrenzt (max. 20 BCC-Empfaenger pro Mail).
-- campaign_id fasst alle BCC-Gruppen einer Auswahl zusammen.
-- bundeslaender enthaelt die Laendercodes der Empfaenger (Dimension Region).

CREATE TABLE IF NOT EXISTS mail_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handoff_id varchar(32) NOT NULL,
    campaign_id varchar(32) NOT NULL,
    batch_number integer NOT NULL,
    batch_count integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by varchar(255),
    subject varchar(255) NOT NULL,
    body text NOT NULL,
    recipients json NOT NULL,
    recipient_count integer NOT NULL,
    bundeslaender json NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'handoff_attempted',
    CONSTRAINT uq_mail_history_handoff_id UNIQUE (handoff_id),
    CONSTRAINT ck_mail_history_recipient_count CHECK (recipient_count BETWEEN 1 AND 20),
    CONSTRAINT ck_mail_history_batch_number CHECK (batch_number BETWEEN 1 AND batch_count),
    CONSTRAINT ck_mail_history_status CHECK (status = 'handoff_attempted')
);

CREATE INDEX IF NOT EXISTS ix_mail_history_created_at ON mail_history (created_at);
CREATE INDEX IF NOT EXISTS ix_mail_history_campaign_id ON mail_history (campaign_id);
